#!/bin/sh
# ci-evidence.sh — collect and commit CI run evidence for a build-i2pd-fork run
# to the ci-evidence branch (never main). Run from the repository root after
# build.log has been accumulated by previous workflow steps.
#
# Usage (from the workflow Record evidence step, or locally for a manual run):
#   WF_NAME=build-i2pd-fork \
#   RUN_URL=https://github.com/.../actions/runs/<id> \
#   S_DEPS=success S_FETCH=success S_PATCHES=success S_BUILD=success S_TESTS=success \
#   SHA=<full commit sha> OVERALL=success \
#   [CLONE_URL=<authenticated clone url>] \
#   i2pd-fork/scripts/ci-evidence.sh
#
# Env (all readable defaults for local dry runs):
#   SHA     full commit sha the run is for
#   OVERALL overall job result: success or failure
#   WF_NAME workflow name
#   RUN_URL URL of the workflow run (for the STATUS.md link)
#   S_DEPS / S_FETCH / S_PATCHES / S_BUILD / S_TESTS: per-step outcome
#          (success|failure|skipped|not_run)
#   CLONE_URL optional; defaults to the remote 'origin' of the repo
#   PUSH push to origin ci-evidence (default 1; set 0 for local dry runs)
#
# Exit status: 0 if all records written; 1 on permission/IO failure.
set -eu

SHA="${SHA:-$(git rev-parse HEAD)}"
OVERALL="${OVERALL:-success}"
WF_NAME="${WF_NAME:-build-i2pd-fork}"
RUN_URL="${RUN_URL:-}"
S_DEPS="${S_DEPS:-not_run}"
S_FETCH="${S_FETCH:-not_run}"
S_PATCHES="${S_PATCHES:-not_run}"
S_BUILD="${S_BUILD:-not_run}"
S_TESTS="${S_TESTS:-not_run}"
PUSH="${PUSH:-1}"
DATE_UTC="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

# result.txt: the definitive record of this run (no silent gaps).
{
  echo "workflow: $WF_NAME"
  echo "run: $RUN_URL"
  echo "commit: $SHA"
  echo "date_utc: $DATE_UTC"
  echo "steps:"
  echo "    checkout: success"
  echo "    install_deps: $S_DEPS"
  echo "    fetch_upstream: $S_FETCH"
  echo "    apply_patches: $S_PATCHES"
  echo "    build: $S_BUILD"
  echo "    unit_tests: $S_TESTS"
  echo "overall: $OVERALL"
} > result.txt

# patches.sha256: receipt of the exact patch contents committed in this repo.
( cd i2pd-fork/patches && sha256sum ./*.patch ) > patches.sha256

# Get (or create) the ci-evidence branch in a scratch checkout.
rm -rf .evidence-workdir
git init -q .evidence-workdir
cd .evidence-workdir
git config user.name "inim-ci"
git config user.email "ci@inim.local"
if [ -n "${CLONE_URL:-}" ]; then
  git remote add origin "$CLONE_URL"
else
  git remote add origin "$(git -C .. remote get-url origin)"
fi
if git fetch -q origin ci-evidence; then
  git checkout -q -b ci-evidence FETCH_HEAD
else
  git checkout -q --orphan ci-evidence
  echo "# CI evidence index" > STATUS.md
fi

mkdir -p "runs/$SHA"
cp ../result.txt ../build.log ../patches.sha256 "runs/$SHA/"

# STATUS.md: newest first, latest 20 runs. Header is fixed lines 1-7.
if ! grep -q '^| commit |' STATUS.md 2>/dev/null; then
  {
    echo '# CI evidence index'
    echo ''
    echo 'Generated by the `build-i2pd-fork` workflow (Record evidence step). To verify any'
    echo 'build/test claim for a commit: read `runs/<sha>/` in this branch.'
    echo ''
    echo '| commit | date_utc | overall | unit_tests | run |'
    echo '|---|---|---|---|---|'
  } > STATUS.md
fi
row="| $SHA | $DATE_UTC | $OVERALL | $S_TESTS | $RUN_URL |"
# Recompose: keep header (first 7 lines), new row, then up to 19 existing rows.
{ sed -n '1,7p' STATUS.md; echo "$row"; sed -n '8,$p' STATUS.md | head -19; } > STATUS.md.tmp
mv STATUS.md.tmp STATUS.md

git add -A
git commit -q -m "evidence: $SHA $OVERALL ($DATE_UTC)"
if [ "$PUSH" = 1 ]; then
  git push -q origin HEAD:ci-evidence
  echo "evidence for $SHA pushed to ci-evidence"
else
  echo "evidence for $SHA recorded locally (PUSH=0)"
fi
cd ..
rm -rf .evidence-workdir